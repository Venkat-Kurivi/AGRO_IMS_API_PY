-- Run this script after creating and connecting to the agro_ims database.
-- It is safe to rerun and does not drop existing data.

CREATE TABLE IF NOT EXISTS branches (
    id VARCHAR(64) PRIMARY KEY,
    name VARCHAR(200) NOT NULL,
    code VARCHAR(20) NOT NULL,
    city VARCHAR(100) NOT NULL,
    phone VARCHAR(50) NOT NULL
);

CREATE TABLE IF NOT EXISTS brands (
    id VARCHAR(64) PRIMARY KEY,
    name VARCHAR(150) NOT NULL,
    origin VARCHAR(150) NOT NULL
);

CREATE TABLE IF NOT EXISTS categories (
    id VARCHAR(64) PRIMARY KEY,
    name VARCHAR(150) NOT NULL,
    description VARCHAR(250) NOT NULL
);

CREATE TABLE IF NOT EXISTS subcategories (
    id VARCHAR(64) PRIMARY KEY,
    name VARCHAR(150) NOT NULL,
    category_id VARCHAR(64) NOT NULL REFERENCES categories(id)
);

CREATE TABLE IF NOT EXISTS customers (
    id VARCHAR(64) PRIMARY KEY,
    name VARCHAR(200) NOT NULL,
    phone VARCHAR(50) NOT NULL,
    email VARCHAR(200) NOT NULL,
    city VARCHAR(100) NOT NULL,
    address VARCHAR(250) NOT NULL DEFAULT ''
);

CREATE TABLE IF NOT EXISTS vendors (
    id VARCHAR(64) PRIMARY KEY,
    name VARCHAR(200) NOT NULL,
    phone VARCHAR(50) NOT NULL,
    email VARCHAR(200) NOT NULL,
    city VARCHAR(100) NOT NULL
);

CREATE TABLE IF NOT EXISTS products (
    id VARCHAR(64) PRIMARY KEY,
    sku VARCHAR(100) NOT NULL,
    name VARCHAR(200) NOT NULL,
    brand_id VARCHAR(64) NOT NULL REFERENCES brands(id),
    category_id VARCHAR(64) NOT NULL REFERENCES categories(id),
    subcategory_id VARCHAR(64) NOT NULL REFERENCES subcategories(id),
    gst NUMERIC(18, 2) NOT NULL CHECK (gst >= 0),
    cost_price NUMERIC(18, 2) NOT NULL CHECK (cost_price >= 0),
    selling_price NUMERIC(18, 2) NOT NULL CHECK (selling_price >= 0)
);

CREATE TABLE IF NOT EXISTS users (
    id VARCHAR(64) PRIMARY KEY,
    name VARCHAR(200) NOT NULL,
    username VARCHAR(100) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    role VARCHAR(20) NOT NULL CHECK (role IN ('Admin', 'Manager')),
    branch_id VARCHAR(64) REFERENCES branches(id),
    active BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS stock_items (
    id VARCHAR(64) PRIMARY KEY,
    product_id VARCHAR(64) NOT NULL REFERENCES products(id),
    branch_id VARCHAR(64) NOT NULL REFERENCES branches(id),
    quantity INTEGER NOT NULL CHECK (quantity >= 0),
    CONSTRAINT uq_stock_product_branch UNIQUE (product_id, branch_id)
);

CREATE TABLE IF NOT EXISTS stock_transactions (
    id VARCHAR(64) PRIMARY KEY,
    date TIMESTAMPTZ NOT NULL,
    product_id VARCHAR(64) NOT NULL REFERENCES products(id),
    branch_id VARCHAR(64) NOT NULL REFERENCES branches(id),
    quantity INTEGER NOT NULL,
    type VARCHAR(24) NOT NULL CHECK (type IN ('Purchase', 'Sale', 'Return', 'Adjustment')),
    reference VARCHAR(100) NOT NULL,
    note VARCHAR(250) NOT NULL
);

CREATE TABLE IF NOT EXISTS purchase_orders (
    id VARCHAR(64) PRIMARY KEY,
    number VARCHAR(100) NOT NULL UNIQUE,
    vendor_id VARCHAR(64) NOT NULL REFERENCES vendors(id),
    branch_id VARCHAR(64) NOT NULL REFERENCES branches(id),
    date TIMESTAMPTZ NOT NULL,
    expected_date TIMESTAMPTZ NOT NULL,
    status VARCHAR(32) NOT NULL CHECK (status IN ('Pending', 'PartiallyReceived', 'Completed')),
    payment_status VARCHAR(24) NOT NULL CHECK (payment_status IN ('Unpaid', 'PartiallyPaid', 'Paid'))
);

CREATE TABLE IF NOT EXISTS purchase_order_items (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    purchase_order_id VARCHAR(64) NOT NULL REFERENCES purchase_orders(id) ON DELETE CASCADE,
    product_id VARCHAR(64) NOT NULL REFERENCES products(id),
    quantity INTEGER NOT NULL CHECK (quantity > 0),
    received INTEGER NOT NULL DEFAULT 0 CHECK (received >= 0 AND received <= quantity),
    unit_cost NUMERIC(18, 2) NOT NULL CHECK (unit_cost >= 0)
);

CREATE TABLE IF NOT EXISTS purchase_receipts (
    id VARCHAR(64) PRIMARY KEY,
    number VARCHAR(100) NOT NULL UNIQUE,
    purchase_order_id VARCHAR(64) NOT NULL REFERENCES purchase_orders(id),
    date TIMESTAMPTZ NOT NULL,
    note VARCHAR(250) NOT NULL
);

CREATE TABLE IF NOT EXISTS purchase_receipt_items (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    purchase_receipt_id VARCHAR(64) NOT NULL REFERENCES purchase_receipts(id) ON DELETE CASCADE,
    product_id VARCHAR(64) NOT NULL REFERENCES products(id),
    quantity INTEGER NOT NULL CHECK (quantity > 0)
);

CREATE TABLE IF NOT EXISTS sales (
    id VARCHAR(64) PRIMARY KEY,
    number VARCHAR(100) NOT NULL UNIQUE,
    customer_id VARCHAR(64) NOT NULL REFERENCES customers(id),
    branch_id VARCHAR(64) NOT NULL REFERENCES branches(id),
    date TIMESTAMPTZ NOT NULL
);

CREATE TABLE IF NOT EXISTS sale_items (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sale_id VARCHAR(64) NOT NULL REFERENCES sales(id) ON DELETE CASCADE,
    product_id VARCHAR(64) NOT NULL REFERENCES products(id),
    quantity INTEGER NOT NULL CHECK (quantity > 0),
    unit_price NUMERIC(18, 2) NOT NULL CHECK (unit_price >= 0),
    unit_cost NUMERIC(18, 2) NOT NULL CHECK (unit_cost >= 0)
);

CREATE TABLE IF NOT EXISTS sales_returns (
    id VARCHAR(64) PRIMARY KEY,
    number VARCHAR(100) NOT NULL UNIQUE,
    sale_id VARCHAR(64) NOT NULL REFERENCES sales(id),
    date TIMESTAMPTZ NOT NULL,
    reason VARCHAR(250) NOT NULL
);

CREATE TABLE IF NOT EXISTS sales_return_items (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sales_return_id VARCHAR(64) NOT NULL REFERENCES sales_returns(id) ON DELETE CASCADE,
    product_id VARCHAR(64) NOT NULL REFERENCES products(id),
    quantity INTEGER NOT NULL CHECK (quantity > 0)
);

CREATE INDEX IF NOT EXISTS ix_subcategories_category_id ON subcategories(category_id);
CREATE INDEX IF NOT EXISTS ix_products_brand_id ON products(brand_id);
CREATE INDEX IF NOT EXISTS ix_products_category_id ON products(category_id);
CREATE INDEX IF NOT EXISTS ix_products_subcategory_id ON products(subcategory_id);
CREATE INDEX IF NOT EXISTS ix_users_branch_id ON users(branch_id);
CREATE INDEX IF NOT EXISTS ix_stock_transactions_date ON stock_transactions(date DESC);
CREATE INDEX IF NOT EXISTS ix_stock_transactions_product_branch ON stock_transactions(product_id, branch_id);
CREATE INDEX IF NOT EXISTS ix_purchase_orders_date ON purchase_orders(date DESC);
CREATE INDEX IF NOT EXISTS ix_purchase_receipts_order_id ON purchase_receipts(purchase_order_id);
CREATE INDEX IF NOT EXISTS ix_sales_date ON sales(date DESC);
CREATE INDEX IF NOT EXISTS ix_sales_returns_sale_id ON sales_returns(sale_id);

